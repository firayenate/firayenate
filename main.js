let currentLang = 'en';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('melkamu_lang', lang);
  
  const dict = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Toggle active class on language toggle buttons
  const enBtn = document.getElementById('lang-en');
  const amBtn = document.getElementById('lang-am');
  if (enBtn && amBtn) {
    if (lang === 'en') {
      enBtn.classList.add('bg-blue-600', 'text-white');
      enBtn.classList.remove('text-slate-600');
      amBtn.classList.remove('bg-blue-600', 'text-white');
      amBtn.classList.add('text-slate-600');
    } else {
      amBtn.classList.add('bg-blue-600', 'text-white');
      amBtn.classList.remove('text-slate-600');
      enBtn.classList.remove('bg-blue-600', 'text-white');
      enBtn.classList.add('text-slate-600');
    }
  }

  // Update html lang attribute
  document.documentElement.lang = lang;
}

